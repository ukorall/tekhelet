package org.tekhelet.knotadvisor.logic

import org.tekhelet.knotadvisor.model.*

/**
 * בודק עד כמה הרכב מסוים "מסתדר עם עצמו".
 *
 * עיקרון מנחה, וחשוב שיישאר כך: **שום הרכב אינו נפסל.** בשורה התחתונה כל צירוף
 * הוא אפשרי - פשוט חלק מהצירופים קצת לא הגיוניים או תרתי דסתרי, ואז ראוי להעיר
 * על זה ולהסביר למה, לא לחסום. הרב שמואל אריאל עצמו עשה בדיוק את זה: הכריע
 * במספר החוטים כראב"ד ובכריכות כרמב"ם, שאל את עצמו "לכאורה שתי ההכרעות סותרות
 * זו את זו", והסביר למה בעצם לא.
 */
object CompositionCoherence {

    enum class Severity { INFO, TENSION }

    data class Remark(
        val severity: Severity,
        val title: String,
        val body: String
    )

    fun review(c: KnotComposition): List<Remark> {
        val out = mutableListOf<Remark>()

        // חצי חוט + סירוגין: הרציונל של חצי חוט הוא שתפקיד התכלת רק לכרוך.
        if (c.threadCount == ThreadCount.RAMBAM_1_OF_8 &&
            (c.windingColor == WindingColor.ALTERNATING_CHULYOT || c.windingColor == WindingColor.ALTERNATING_WINDS)
        ) {
            out += Remark(
                Severity.TENSION,
                "חצי חוט יחד עם כריכות לסירוגין",
                "ההסתפקות בחצי חוט תכלת נובעת מהתפיסה שתפקיד התכלת הוא לכרוך את חוטי הלבן - " +
                    "ואם זה התפקיד, מתבקש שרוב הכריכות יהיו בתכלת. הרב יעקב נגן כותב את זה " +
                    "במפורש: מי שנוהג כרמב\"ם במספר הפתילים צריך לעשות את הכריכות כשיטתו. " +
                    "אפשר בהחלט לעשות אחרת, רק כדאי שתדע שזה מושך לשני כיוונים."
            )
        }

        // חוליות תימניות + חמישה קשרים: התימנים לא עשו חמישה קשרים מלכתחילה.
        if (c.chulyaForm == ChulyaForm.YEMENITE_SELF_HOLDING &&
            c.knotScheme in setOf(
                KnotScheme.FIVE_GROUPS_CHINUCH, KnotScheme.FIVE_GROUPS_GRA,
                KnotScheme.FIVE_GROUPS_TOSAFOT, KnotScheme.FIVE_WINDS_7_8_11_13
            )
        ) {
            out += Remark(
                Severity.INFO,
                "חוליה תימנית יחד עם חמישה קשרים",
                "מנהג התימנים היה במקור בלי חמישה קשרים - החוליה מחזיקה את עצמה ואין קשר ביניהן. " +
                    "הרב רפמן מביא מקור לסמוך עליו בשעת הדחק לשלב את השניים, ומצד שני כותב שבזמן " +
                    "שיש תכלת גם בני תימן צריכים חמישה קשרים. כלומר: אפשרי, ויש על מה לסמוך, " +
                    "אבל זה לא הצירוף ההיסטורי."
            )
        }

        // קשרים לפי כריכות ולא חוליות: פוגע ב"היכר חוליות".
        if (c.knotScheme == KnotScheme.FIVE_WINDS_7_8_11_13) {
            out += Remark(
                Severity.INFO,
                "הקשרים מחלקים כריכות ולא חוליות",
                "בחלוקה הזו הקשר יכול ליפול באמצע חוליה. הרב רפמן מסתייג מזה, כי בתכלת יש עניין " +
                    "של \"היכר חוליות\" שלא קיים בלבן, וקשר באמצע חוליה הוא היפוכו. מי שנוהג כך " +
                    "צריך לפחות להקפיד על רווח ברור בין החוליות."
            )
        }

        // ארבע חוליות בלבד - זה מנהג הלבן, לא דין הגמרא בתכלת.
        if (c.chulyotCount == ChulyotCount.FOUR) {
            out += Remark(
                Severity.TENSION,
                "ארבע חוליות זה מנהג הלבן",
                "דין הגמרא בתכלת הוא שבע עד שלוש עשרה חוליות, כשכל חוליה שלוש כריכות לפחות. " +
                    "החלוקה לארבע קבוצות כריכות היא המנהג שנוצר בלבן, אחרי שהתכלת נגנזה. " +
                    "גם הרב אריאל וגם הרב רפמן מדגישים שאי אפשר ללמוד ממנהגי הלבן לתכלת."
            )
        }

        // ארבעה חוטים (תוספות) - התכלת כבר לא "הכורך".
        if (c.threadCount == ThreadCount.TOSAFOT_4_OF_8 &&
            c.windingColor == WindingColor.MOSTLY_TEKHELET_SINGLE_WIND
        ) {
            out += Remark(
                Severity.INFO,
                "ארבעה חוטי תכלת יחד עם כריכות כרמב\"ם",
                "לפי תוספות, שיש שני חוטי תכלת, ודאי שאין תפקיד התכלת לכרוך - שאם כן, למה נוסף " +
                    "עוד חוט תכלת שאין לו תפקיד בכריכה. הצירוף אפשרי, אבל הוא מאמץ את מספר החוטים " +
                    "של תוספות ואת תפיסת התכלת של הרמב\"ם."
            )
        }

        return out
    }

    /**
     * הדין היחיד שלא כדאי לוותר עליו בשום הרכב: הכריכה הראשונה והאחרונה בלבן.
     * זו גמרא מפורשת (מנחות ל"ט ע"א) - "כשהוא מתחיל מתחיל בלבן... וכשהוא מסיים
     * מסיים בלבן" - והרבה אנשים טועים בזה דווקא כשהם קושרים "כמו בלבן".
     */
    fun alwaysRemember(): Remark = Remark(
        Severity.TENSION,
        "מתחילים בלבן ומסיימים בלבן",
        "זה נכון לכל שיטה בלי יוצא מן הכלל, וזו גמרא מפורשת: \"תנא, כשהוא מתחיל - מתחיל בלבן, " +
            "'הכנף' מין כנף; וכשהוא מסיים - מסיים בלבן, מעלין בקודש ולא מורידין\" (מנחות ל\"ט ע\"א). " +
            "הרבה אנשים טועים בזה, במיוחד מי שקושר כמו שהוא רגיל בלבן ופשוט מחליף את צבע הכריכות. " +
            "גם אם בחרת בהרכב הכי שמרני שיש - הליפוף הראשון והאחרון חייבים להיות לבנים."
    )
}
