package org.tekhelet.knotadvisor.model

import kotlinx.serialization.Serializable

/**
 * שכבת ה"הרכב ההלכתי" של שיטת קשירה.
 *
 * התובנה המרכזית מהמקורות (הרב שמואל אריאל, "התכלת וחידושה", פרק ז): הטלת תכלת
 * אינה בחירה של "שיטה" אטומית אחת מתוך רשימה, אלא **חמישה דיונים נפרדים**, שכל
 * שיטה מוכרת היא צירוף מסוים של הכרעות בהם. בלשונו:
 *
 *   "מכיוון שיש כאן חמישה דיונים נפרדים, הרי מספר השיטות האפשריות הוא גדול מאד,
 *    שהרי כל שיטת קשירה צריכה לשלב הכרעה מסויימת בדיון א' יחד עם הכרעה מסויימת
 *    בדיון ב' וכן הלאה. ובפועל אכן מצינו בפוסקים שבע שיטות שונות ואף יותר."
 *
 * זה בדיוק המבנה של התרשים שאוריאל הכין (ראו content/diagram/). לכן המודל כאן
 * מפריד בין שתי שכבות שונות לגמרי:
 *  - `axisScores` (ב-KnotMethod) - שכבה **סובייקטיבית**: כמה השיטה "יפה"/"נפוצה"/
 *    "מבוססת", לצורך התאמה להעדפות המשתמש בשאלון.
 *  - `KnotComposition` (כאן) - שכבה **עובדתית**: ממה השיטה מורכבת בפועל.
 *
 * ההפרדה הזו היא מה שיאפשר בהמשך: סינון לפי הכרעה קודמת (אזור "כמה" מזין את
 * אזור "איך"), הצגת הוראות קשירה מדויקות, והשוואת שיטות דיון-מול-דיון.
 */
@Serializable
data class KnotComposition(
    val threadCount: ThreadCount? = null,
    val windingColor: WindingColor? = null,
    val chulyotCount: ChulyotCount? = null,
    val chulyaForm: ChulyaForm? = null,
    val knotScheme: KnotScheme? = null,
    /** רצף הכריכות בפועל, אם ידוע במדויק. למשל [5,5,6,6,6,6,6] אצל הרב אריאל. */
    val windsPerChulya: List<Int> = emptyList(),
    /** הערה חופשית על ההרכב, למשל אי-ודאות או וריאציות מקובלות. */
    val note: String? = null
)

/**
 * דיון א' - מספר חוטי התכלת מתוך שמונה.
 *
 * זה הדיון היחיד שהוא **מעכב**: "אם הטיל מספר חוטי תכלת לפי דעה המצמצמת את
 * מספרם, לא יצא ידי חובה לפי הדעות הדורשות יותר חוטי תכלת" (הרב אריאל).
 * שאר הדיונים אינם מעכבים. ההבחנה הזו קריטית להצגה למשתמש - ראו BindingLevel.
 */
@Serializable
enum class ThreadCount(val label: String, val attribution: String) {
    RAMBAM_1_OF_8("חצי חוט - 1 מתוך 8", "רמב\"ם"),
    RAAVAD_2_OF_8("חוט שלם - 2 מתוך 8", "ראב\"ד, הערוך, הגר\"א"),
    TOSAFOT_4_OF_8("שני חוטים - 4 מתוך 8", "רש\"י, תוספות ורוב הראשונים")
}

/** דיון ב' - האם הכריכות בעיקר בתכלת, או תכלת ולבן לסירוגין. */
@Serializable
enum class WindingColor(val label: String, val attribution: String) {
    MOSTLY_TEKHELET_SINGLE_WIND(
        "רוב הכריכות בתכלת; רק הכריכה הראשונה והאחרונה בלבן", "רמב\"ם"
    ),
    MOSTLY_TEKHELET_FULL_CHULYA(
        "רוב החוליות בתכלת; החוליה הראשונה והאחרונה כולה לבן", "לפי הסוברים שמתחיל בחוליה שלמה"
    ),
    ALTERNATING_CHULYOT(
        "חוליות תכלת ולבן לסירוגין, מתחיל ומסיים בלבן", "רב עמרם גאון, תוספות, הגר\"א"
    ),
    ALTERNATING_WINDS(
        "כריכות תכלת ולבן לסירוגין בתוך כל חוליה", "ראב\"ד"
    )
}

/** דיון ג' - מספר החוליות (הגמרא: "הפוחת לא יפחות משבע והמוסיף לא יוסיף על שלש עשרה"). */
@Serializable
enum class ChulyotCount(val label: String) {
    SEVEN("7 חוליות"),
    THIRTEEN("13 חוליות"),
    SEVEN_OR_THIRTEEN("7 או 13 חוליות"),
    FOUR("4 חוליות")
}

/**
 * דיון ד' - צורת החוליה.
 *
 * נקודה שעלתה גם בשו"ת שאוריאל שלח (שאלת דניאל לרב שמואל אריאל): גם הרב אריאל
 * וגם הרב רפמן סוברים שמי שאינו תימני אין לו סיבה לאמץ חוליות תימניות, ושראוי
 * להפריד בין החוליות באותו אופן שנהגו האבות - בקשרים כפולים.
 */
@Serializable
enum class ChulyaForm(val label: String, val attribution: String) {
    STANDARD_DOUBLE_KNOT("קשר כפול בין חוליה לחוליה", "מנהג אשכנז וספרד"),
    YEMENITE_SELF_HOLDING("חוליה תימנית - מחזיקה את עצמה, בלי קשר ביניהן", "מנהג תימן (בלדי), מקורו ברמב\"ם"),
    YEMENITE_INVERTED("חוליה תימנית הפוכה - כך שאינה מחזיקה את עצמה", "חב\"ד / ראדזין"),
    TUCK_BETWEEN_THREADS("תחיבת החוט הכורך בין החוטים", "סמ\"ק, לקט יושר, מנהג סלאנים")
}

/** דיון ה' - שילוב חמשת הקשרים עם החוליות. */
@Serializable
enum class KnotScheme(val label: String, val attribution: String) {
    NONE("בלי חמישה קשרים - רק קשר בהתחלה ובסוף", "כיוון ד' אצל הרב אריאל; הרמב\"ם לא הזכיר ה' קשרים"),
    PAIRS_2_2_2_1("הקשרים מחלקים את החוליות ל-2,2,2,1", "תוספות"),
    GROUPS_3_3_3_4("הקשרים מחלקים את החוליות ל-3,3,3,4", "ספר החינוך, מהר\"ם די לונזאנו"),
    GROUPS_4_4_4_1("הקשרים מחלקים את החוליות ל-4,4,4,1", "הגר\"א על הזוהר"),
    WINDS_7_8_11_13("הקשרים מחלקים את הכריכות (לא החוליות) ל-7,8,11,13", "האר\"י, ראדזין"),
    KNOT_EVERY_CHULYA("קשר כפול אחרי כל חוליה", "הרב שמואל אריאל; ראב\"ד")
}

/**
 * עד כמה ההכרעה בדיון מסוים באמת מחייבת. מבוסס במפורש על הרב אריאל: דיון א'
 * (מספר החוטים) הוא היחיד שהוא לעיכובא; שאר הדיונים הם לכתחילה/הידור בלבד.
 * מוצג למשתמש כדי שלא יתייסר על החלטות שאין להן משקל הלכתי אמיתי.
 */
@Serializable
enum class BindingLevel(val label: String, val explanation: String) {
    BINDING(
        "מעכב",
        "הכרעה בדיון הזה משפיעה על עצם קיום המצווה לפי חלק מהדעות - כאן באמת חשוב לדעת במה בחרת."
    ),
    PREFERRED(
        "לכתחילה",
        "אינו מעכב: כמעט בכל אופן שתעשה יצאת ידי חובה לפי כל הדעות, גם אם אין זה לכתחילה."
    ),
    ADORNMENT(
        "נוי מצווה",
        "עניין של הידור וסמליות בלבד - כאן העיקרון המנחה הוא \"זה אלי ואנוהו\"."
    )
}

/** מיפוי קבוע: לכל דיון, מה רמת המחייבות שלו. */
object DecisionBinding {
    val threadCount = BindingLevel.BINDING
    val windingColor = BindingLevel.PREFERRED
    val chulyotCount = BindingLevel.PREFERRED
    val chulyaForm = BindingLevel.ADORNMENT
    val knotScheme = BindingLevel.PREFERRED
}
