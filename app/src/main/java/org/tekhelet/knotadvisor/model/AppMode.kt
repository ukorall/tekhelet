package org.tekhelet.knotadvisor.model

/**
 * שני מצבי תאורה.
 *
 * **מנהלתי** - המצב הרגיל, על נייר בהיר.
 *
 * **מבצעי** - למי שמסתכל על זה בשטח או בחושך. התכלת נשארת תכלת בדיוק כפי
 * שהיא, הלבן (כולל חוטי הליבה) הופך לירוק זית כהה, התכלת הבהירה לירוק זית
 * בהיר, והטקסטים לבנים.
 *
 * מהותית זה מצב לילה. השמות הם בחירה של אוריאל, לא תיאור טכני, ואין טעם
 * להעמיד פנים אחרת בקוד. מה שכן נכון טכנית: הבחירה מפורשת ונשמרת, ולא נגזרת
 * מהגדרת המערכת - אם נרצה שההפעלה הראשונה תלך אחרי הגדרת המכשיר, זה צריך
 * מצב שלישי "לא נבחר" ולא ברירת מחדל שקטה שתדרוס בחירה קיימת.
 */
enum class AppMode(val label: String, val blurb: String) {
    ADMIN("מנהלתי", "נייר בהיר. מצב ברירת המחדל."),
    OPERATIONAL("מבצעי", "ירוק זית וטקסט לבן. התכלת נשארת תכלת.")
}
